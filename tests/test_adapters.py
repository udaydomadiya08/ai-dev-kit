def test_deterministic_generation(mock_context: GenerationContext):
    """Ensure identical inputs always produce byte-for-byte identical outputs."""
    for adapter_id in get_available_adapter_ids():
        adapter = get_adapter(adapter_id)
        assert adapter is not None
        out1 = adapter.generate(mock_context)
        out2 = adapter.generate(mock_context)
        assert out1 == out2, f"Adapter {adapter_id} generation is non-deterministic"
