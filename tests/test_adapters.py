def test_opencode_adapter(mock_context: GenerationContext):
    adapter = OpenCodeAdapter()
    output = adapter.generate(mock_context)

    assert "opencode.json" in output
    assert ".opencode/instructions.md" in output
    assert ".opencode/safety.md" in output

    # Validate json structure
    parsed = json.loads(output["opencode.json"])
    assert parsed["name"] == "test-repo"
    assert parsed["profile"] == "python"
    assert "commands" in parsed
    assert parsed["commands"]["test"] == "pytest"


