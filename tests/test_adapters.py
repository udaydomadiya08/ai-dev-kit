def test_registry_contains_all_adapters():
    adapter_ids = get_available_adapter_ids()
    assert "agents-md" in adapter_ids
    assert "claude-code" in adapter_ids
    assert "antigravity" in adapter_ids
    assert "cursor" in adapter_ids
    assert "opencode" in adapter_ids
    assert "generic" in adapter_ids

    adapters = list_adapters()
    assert len(adapters) >= 6
    for adapter in adapters:
        assert adapter.id
        assert adapter.name
        assert adapter.description
        assert len(adapter.supported_artifacts()) > 0


