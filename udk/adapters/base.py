"""
Base adapter definitions for Universal AI Dev Kit (UDK).
Each agent adapter transforms canonical knowledge and profiles into
native configuration artifacts for a specific AI agent or editor.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any


@dataclass
class Diagnostic:
    severity: str  # "error", "warning", "info"
    message: str
    file_path: str | None = None
    code: str | None = None

    def __str__(self) -> str:
        loc = f"[{self.file_path}] " if self.file_path else ""
        return f"[{self.severity.upper()}] {loc}{self.message}"


@dataclass
class GenerationContext:
    workspace_root: Path
    project_name: str
    profile_name: str
    profile_data: dict[str, Any]
    principles: str
    engineering: str
    workflow: str
    safety: str
    instructions: dict[str, str] = field(default_factory=dict)
    skills: dict[str, dict[str, Any]] = field(default_factory=dict)
    custom_vars: dict[str, Any] = field(default_factory=dict)
    toolkit_version: str = "0.1.0"


class AgentAdapter(ABC):
    """Abstract base class for all target agent configuration compilers."""

    @property
    @abstractmethod
    def id(self) -> str:
        """Unique slug identifier for the adapter (e.g. 'agents-md', 'claude-code')."""

    @property
    @abstractmethod
    def name(self) -> str:
        """Human-readable display name for the adapter."""

    @property
    @abstractmethod
    def description(self) -> str:
        """Short summary of target agent and files produced."""

    @abstractmethod
    def supported_artifacts(self) -> list[str]:
        """List of relative paths this adapter generates or manages."""

    @abstractmethod
    def generate(self, context: GenerationContext) -> dict[str, str]:
        """
        Compiles canonical knowledge into target files.
        Returns mapping: relative_file_path -> text_content.
        """

    def validate(self, workspace_root: Path) -> list[Diagnostic]:
        """
        Validates target artifacts existing on disk for syntax and consistency.
        Default implementation checks existence of supported artifacts.
        """
        diagnostics: list[Diagnostic] = []
        for artifact in self.supported_artifacts():
            full_path = workspace_root / artifact
            if not full_path.exists():
                diagnostics.append(
                    Diagnostic(
                        severity="warning",
                        file_path=artifact,
                        message=f"Expected artifact '{artifact}' for adapter '{self.id}' is missing.",
                        code="MISSING_ARTIFACT",
                    )
                )
        return diagnostics

    def banner(self, extra: str = "") -> str:
        """Returns standard machine-readable banner prepended to generated files."""
        extra_note = f" - {extra}" if extra else ""
        return (
            "<!-- \n"
            f"Generated by Universal AI Dev Kit (udk) [Adapter: {self.id}]{extra_note}\n"
            "Canonical source of truth is managed by UDK. To customize, run 'udk diff' or edit .udk/.\n"
            "-->\n\n"
        )
